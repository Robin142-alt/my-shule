import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { ReportsWorkspace } from '@/components/school/accountant/reports-workspace';
import { WaiversDiscountsWorkspace } from '@/components/school/accountant/waivers-discounts-workspace';
import { requestDashboardApi } from '@/lib/dashboard/api-client';
import { downloadTextFile, openPrintDocument } from '@/lib/dashboard/export';
jest.mock('@/lib/dashboard/api-client',()=>({requestDashboardApi:jest.fn().mockResolvedValue({})}));
jest.mock('@/lib/data/school-tenant-scope',()=>({useOptionalSchoolTenantId:()=> 'school-a'}));
jest.mock('@/components/providers/permission-context',()=>({usePermissions:()=>({hasPermission:()=>true})}));
jest.mock('@/components/school/integrated-school-command-header',()=>({useSchoolCommandIdentity:()=>({schoolName:'School A',userLabel:'Accountant'})}));
jest.mock('@/lib/dashboard/export',()=>({downloadTextFile:jest.fn(),openPrintDocument:jest.fn()}));
jest.mock('@/components/common/learner-picker',()=>({LearnerPicker:({onChange}:any)=><button type="button" onClick={()=>onChange({id:'student',name:'Amina',admissionNumber:'001'})}>Choose Amina</button>}));
const artifact={filename:'reconciliation.csv',content_type:'text/csv',csv:'Learner,Amount\nAmina,10.00',row_count:1};
beforeEach(()=>{jest.clearAllMocks();global.fetch=jest.fn().mockResolvedValue({ok:true,json:async()=>({data:artifact})});});
test('report preview and download unwrap real API responses and preserve chosen filters',async()=>{
  render(<ReportsWorkspace role="accountant" tenantSlug="school-a"/>);
  fireEvent.change(screen.getByLabelText('From'),{target:{value:'2026-10-01'}});
  fireEvent.change(screen.getByLabelText('To'),{target:{value:'2026-10-12'}});
  fireEvent.change(screen.getByLabelText('Payment method'),{target:{value:'cash'}});
  fireEvent.click(screen.getAllByRole('button',{name:'Preview & print'})[1]);
  await waitFor(()=>expect(openPrintDocument).toHaveBeenCalled());
  fireEvent.click(screen.getAllByRole('button',{name:'Download CSV'})[1]);
  await waitFor(()=>expect(downloadTextFile).toHaveBeenCalled());
  const calls=(fetch as jest.Mock).mock.calls;
  expect(calls[0][0]).toBe(calls[1][0]);
  expect(calls[0][0]).toContain('from=2026-10-01&to=2026-10-12&method=cash');
  expect(openPrintDocument).toHaveBeenCalledWith(expect.objectContaining({rows:[{label:'Amina',value:'Amount: 10.00'}]}));
});
test('invalid report period prevents requests, and failed exports do not claim success',async()=>{
  render(<ReportsWorkspace role="accountant"/>);
  fireEvent.change(screen.getByLabelText('From'),{target:{value:'2026-12-31'}});
  fireEvent.change(screen.getByLabelText('To'),{target:{value:'2026-10-01'}});
  expect(screen.getAllByRole('button',{name:'Download CSV'})[1]).toBeDisabled();
  (fetch as jest.Mock).mockResolvedValue({ok:false,json:async()=>({message:'Export unavailable'})});
  fireEvent.click(screen.getAllByRole('button',{name:'Download CSV'})[0]);
  await screen.findByText('Export unavailable');
  expect(downloadTextFile).not.toHaveBeenCalled();
});
test('waiver errors offer retry, wrapped rows render, and requests reuse their reference after failure',async()=>{
  (fetch as jest.Mock).mockRejectedValueOnce(new Error('Register offline')).mockResolvedValue({ok:true,json:async()=>({data:[{id:'waiver',student_name:'Amina',reason:'Scholarship',amount_minor:'1000',status:'pending',created_at:'2026-10-01'}]})});
  (requestDashboardApi as jest.Mock).mockRejectedValueOnce(new Error('Request interrupted')).mockResolvedValueOnce({message:'Sent to Principal. Balance unchanged.'});
  render(<WaiversDiscountsWorkspace role="accountant" tenantSlug="school-a"/>);
  await screen.findByText('Register offline');
  fireEvent.click(screen.getByRole('button',{name:'Retry waivers'}));
  await screen.findAllByText('Amina');
  fireEvent.click(screen.getByRole('button',{name:'Request fee waiver'}));
  fireEvent.click(screen.getByRole('button',{name:'Choose Amina'}));
  fireEvent.change(screen.getByLabelText('Amount (KES)'),{target:{value:'10'}});
  fireEvent.change(screen.getByLabelText('Reason'),{target:{value:'Scholarship'}});
  fireEvent.click(screen.getByRole('button',{name:'Submit request'}));
  await screen.findByText('Request interrupted');
  fireEvent.click(screen.getByRole('button',{name:'Submit request'}));
  await screen.findByText('Sent to Principal. Balance unchanged.');
  const calls=(requestDashboardApi as jest.Mock).mock.calls;
  expect(calls[0]).toEqual(calls[1]);
  expect(calls[0][1].body).toEqual({student_id:'student',student_name:'Amina',amount_minor:'1000',reason:'Scholarship',idempotency_key:expect.any(String)});
});
